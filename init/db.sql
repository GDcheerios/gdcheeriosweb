-- ==========================================
-- 3. ACCOUNT SCHEMA (Identity)
-- ==========================================
CREATE TABLE account.users
(
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        text                                                       NOT NULL,
    password        text                                                       NOT NULL,
    email           text                                                       NOT NULL,
    about           text,
    status          account.status              DEFAULT 'user'::account.status NOT NULL,
    created         timestamp without time zone DEFAULT now(),
    is_supporter    boolean                     DEFAULT false                  NOT NULL,
    last_support    timestamp with time zone,
    supporter_lasts timestamp with time zone,
    is_admin        boolean                     DEFAULT false                  NOT NULL
);

CREATE TABLE account.tags
(
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer NOT NULL REFERENCES account.users (id) ON DELETE CASCADE,
    title      text    NOT NULL,
    type       text    NOT NULL
);

CREATE TABLE account.supports
(
    id           uuid                     DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id      integer                                NOT NULL REFERENCES account.users (id) ON DELETE CASCADE,
    weeks        integer                  DEFAULT 1     NOT NULL,
    supported_on timestamp with time zone DEFAULT now() NOT NULL
);

CREATE TABLE account.pending
(
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text                                                            NOT NULL,
    email    text                                                            NOT NULL,
    about    text,
    password text                                                            NOT NULL,
    sent     timestamp with time zone DEFAULT now()                          NOT NULL,
    expires  timestamp with time zone DEFAULT (now() + '24:00:00'::interval) NOT NULL,
    token    text                                                            NOT NULL
);

CREATE TABLE account.sessions
(
    id         uuid                     DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id    integer                                NOT NULL REFERENCES account.users (id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

CREATE TABLE account.password_resets
(
    id         uuid                     DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id    integer                                                         NOT NULL REFERENCES account.users (id) ON DELETE CASCADE,
    expires_at timestamp with time zone DEFAULT (now() + '01:00:00'::interval) NOT NULL
);

-- ==========================================
-- 4. AUTH SCHEMA (Security & Access)
-- ==========================================
CREATE TABLE auth.identities
(
    id               uuid                     DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id          integer                                NOT NULL REFERENCES account.users (id) ON DELETE CASCADE,
    provider         text                                   NOT NULL,
    provider_subject text                                   NOT NULL,
    created_at       timestamp with time zone DEFAULT now() NOT NULL
);

-- ==========================================
-- 5. API SCHEMA (System Keys & Logging)
-- ==========================================
CREATE TABLE api.keys
(
    id                       uuid                     DEFAULT gen_random_uuid() PRIMARY KEY,
    key_id                   text UNIQUE                                               NOT NULL,
    secret_hash              text                                                      NOT NULL,
    name                     text,
    scopes                   jsonb                    DEFAULT '[]'::jsonb              NOT NULL,
    created_at               timestamp with time zone DEFAULT now()                    NOT NULL,
    last_used_at             timestamp with time zone,
    expires_at               timestamp with time zone,
    status                   api.key_status           DEFAULT 'active'::api.key_status NOT NULL,
    created_by_ip            inet,
    last_used_ip             inet,
    metadata                 jsonb,
    user_id                  integer REFERENCES account.users (id) ON DELETE CASCADE,
    refresh_token_hash       text,
    refresh_token_expires_at timestamp with time zone,
    last_refreshed_at        timestamp with time zone,
    rotated_from_key_id      text
);

CREATE INDEX idx_api_keys_last_used_at ON api.keys USING btree (last_used_at);
CREATE INDEX idx_api_keys_status ON api.keys USING btree (status);

-- ==========================================
-- 6. GQ SCHEMA (Gentry's Quest)
-- ==========================================
CREATE TABLE gq.profiles
(
    account_id integer PRIMARY KEY REFERENCES account.users (id) ON DELETE CASCADE,
    money      bigint   DEFAULT 0                NOT NULL,
    weighted   smallint DEFAULT 0                NOT NULL,
    unweighted integer  DEFAULT 0                NOT NULL,
    rank       text     DEFAULT 'unranked'::text NOT NULL,
    tier       smallint DEFAULT 0                NOT NULL
);

CREATE TABLE gq.items
(
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metadata jsonb                                 NOT NULL,
    rating   integer                     DEFAULT 0 NOT NULL,
    owner_id integer REFERENCES account.users (id) ON DELETE CASCADE,
    is_new   boolean                     DEFAULT false,
    obtained timestamp without time zone DEFAULT now()
);

CREATE TABLE gq.leaderboards
(
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   text    NOT NULL,
    online boolean NOT NULL
);

CREATE TABLE gq.visitations
(
    id       uuid                     DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id  integer REFERENCES account.users (id) ON DELETE CASCADE,
    location text,
    arrived  timestamp with time zone DEFAULT now() NOT NULL,
    departed timestamp with time zone
);

CREATE TABLE gq.scores
(
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           text                                   NOT NULL,
    score          bigint                                 NOT NULL,
    leaderboard_id integer                                NOT NULL REFERENCES gq.leaderboards (id) ON DELETE CASCADE,
    user_id        integer REFERENCES account.users (id) ON DELETE CASCADE,
    submitted_at   timestamp with time zone DEFAULT now() NOT NULL,
    visitation_id  uuid                                   REFERENCES gq.visitations (id) ON DELETE SET NULL
);

CREATE TABLE gq.statistics
(
    id             uuid                     DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id        integer                                NOT NULL REFERENCES account.users (id) ON DELETE CASCADE,
    type           gq.statistic_type                      NOT NULL,
    amount         integer                  DEFAULT 0     NOT NULL,
    enemy          text                     DEFAULT null,
    character      text                     DEFAULT null,
    weapon         text                     DEFAULT null,
    location       text                     DEFAULT null,
    status_effect  text                     DEFAULT null,
    visitation_id  uuid                                   REFERENCES gq.visitations (id) ON DELETE SET NULL,
    leaderboard_id integer                                REFERENCES gq.leaderboards (id) ON DELETE SET NULL,
    happened       timestamp with time zone DEFAULT now() NOT NULL
);

CREATE INDEX idx_gq_stats_user ON gq.statistics USING btree (user_id);

CREATE TABLE gq.metrics
(
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer REFERENCES account.users (id) ON DELETE CASCADE,
    recorded_at date    DEFAULT now() NOT NULL,
    rank        integer DEFAULT 0     NOT NULL,
    gp          integer DEFAULT 0     NOT NULL
);

