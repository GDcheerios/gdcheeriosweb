(
    match_id         integer                      not null
        references osu.matches
            on delete cascade,
    user_id          bigint                       not null
        references osu.users
            on delete cascade,
    nickname         text,
    team_id          integer
        constraint match_users_teams_id_fk
            references osu.teams
            on update set null on delete set null,
    starting_stats   jsonb    default '{}'::jsonb not null,
    ending_stats     jsonb,
    reconstructed_pp integer  default 0           not null,
    placement        smallint default 0           not null,
    primary key (match_id, user_id)
);

create table osu.match_metrics
(
    match_id  integer               not null
        constraint match_metrics_matches_id_fk
            references osu.matches
            on delete cascade,
    user_id   integer               not null
        constraint match_metrics_users_id_fk
            references osu.users,
    placement integer default 0     not null,
    objective numeric default 0     not null,
    plays     integer default 0     not null,
    date      date    default now() not null,
    constraint match_metrics_pk
        unique (user_id, match_id, date)
);

create function osu.set_match_ended_at() returns trigger
    language plpgsql
as
$$
BEGIN
    IF NEW.ended = TRUE AND (OLD.ended IS FALSE OR OLD.ended IS NULL) THEN
        IF NEW.ended_at IS NULL OR NEW.ended_at = OLD.ended_at THEN
            NEW.ended_at := NOW();
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

create trigger trg_set_match_ended_at
    before update
    on osu.matches
    for each row
    when (new.ended IS TRUE AND (old.ended IS FALSE OR old.ended IS NULL))
execute procedure osu.set_match_ended_at();

